import { jsPDF } from "jspdf";
import { SUBJECTS } from "../data/seed.js";
import { average, computeGPA, creditsFor, fmtGPA, scoreToLetter, scoreToPoints } from "./academic.js";

const INDIGO = [79, 70, 229];
const SLATE = [51, 65, 85];
const LIGHT = [241, 245, 249];

function header(doc, title, subtitle) {
  const w = doc.internal.pageSize.getWidth();
  doc.setFillColor(...INDIGO);
  doc.rect(0, 0, w, 34, "F");
  doc.setTextColor(255, 255, 255);
  doc.setFont("helvetica", "bold");
  doc.setFontSize(20);
  doc.text("EduSphere AI", 14, 15);
  doc.setFont("helvetica", "normal");
  doc.setFontSize(10);
  doc.text("School Automation & Intelligence", 14, 22);
  doc.setFontSize(13);
  doc.setFont("helvetica", "bold");
  doc.text(title, w - 14, 15, { align: "right" });
  doc.setFont("helvetica", "normal");
  doc.setFontSize(9);
  if (subtitle) doc.text(subtitle, w - 14, 22, { align: "right" });
  doc.setTextColor(...SLATE);
}

function footer(doc) {
  const pages = doc.getNumberOfPages();
  const w = doc.internal.pageSize.getWidth();
  const h = doc.internal.pageSize.getHeight();
  for (let i = 1; i <= pages; i++) {
    doc.setPage(i);
    doc.setDrawColor(203, 213, 225);
    doc.line(14, h - 14, w - 14, h - 14);
    doc.setFontSize(8);
    doc.setTextColor(100, 116, 139);
    doc.text(`Generated by EduSphere AI on ${new Date().toLocaleString()}`, 14, h - 8);
    doc.text(`Page ${i} of ${pages}`, w - 14, h - 8, { align: "right" });
  }
}

function tableHeader(doc, y, cols) {
  const w = doc.internal.pageSize.getWidth();
  doc.setFillColor(...INDIGO);
  doc.rect(14, y, w - 28, 8, "F");
  doc.setTextColor(255, 255, 255);
  doc.setFont("helvetica", "bold");
  doc.setFontSize(9);
  cols.forEach((c) => doc.text(c.label, c.x, y + 5.5, { align: c.align || "left" }));
  doc.setFont("helvetica", "normal");
  doc.setTextColor(...SLATE);
  return y + 8;
}

function tableRow(doc, y, cols, values, shaded) {
  const w = doc.internal.pageSize.getWidth();
  if (shaded) {
    doc.setFillColor(...LIGHT);
    doc.rect(14, y, w - 28, 8, "F");
  }
  doc.setFontSize(9);
  cols.forEach((c, i) => {
    const text = String(values[i] ?? "");
    doc.text(text.length > (c.max || 60) ? text.slice(0, (c.max || 60) - 1) + "…" : text, c.x, y + 5.5, { align: c.align || "left" });
  });
  return y + 8;
}

function paged(doc, y, cols, rows) {
  const h = doc.internal.pageSize.getHeight();
  y = tableHeader(doc, y, cols);
  rows.forEach((r, i) => {
    if (y > h - 24) {
      doc.addPage();
      y = tableHeader(doc, 16, cols);
    }
    y = tableRow(doc, y, cols, r, i % 2 === 1);
  });
  return y;
}

export function studentReport(student) {
  const doc = new jsPDF();
  const w = doc.internal.pageSize.getWidth();
  header(doc, "Student Report Card", `Academic year ${new Date().getFullYear()}`);

  doc.setFont("helvetica", "bold");
  doc.setFontSize(16);
  doc.text(student.name, 14, 48);
  doc.setFont("helvetica", "normal");
  doc.setFontSize(10);
  const info = [
    ["Student ID", student.id],
    ["Class", student.cls],
    ["Date of birth", student.dob || "-"],
    ["Guardian", student.guardian || "-"],
    ["Contact", student.phone || "-"],
    ["Attendance", `${student.attendance}%`],
  ];
  info.forEach(([k, v], i) => {
    const col = i % 2;
    const row = Math.floor(i / 2);
    const x = 14 + col * 95;
    const y = 58 + row * 7;
    doc.setFont("helvetica", "bold");
    doc.text(k + ":", x, y);
    doc.setFont("helvetica", "normal");
    doc.text(String(v), x + 30, y);
  });

  const cols = [
    { label: "Subject", x: 17 },
    { label: "Credits", x: 85, align: "center" },
    { label: "Score (%)", x: 115, align: "center" },
    { label: "Grade", x: 147, align: "center" },
    { label: "Points", x: 180, align: "center" },
  ];
  const subjects = Object.keys(student.grades || {}).filter((k) => student.grades[k] !== "");
  const rows = subjects.map((s) => [
    s,
    creditsFor(s),
    student.grades[s],
    scoreToLetter(student.grades[s]),
    scoreToPoints(student.grades[s]).toFixed(1),
  ]);
  let y = paged(doc, 84, cols, rows);

  const gpa = computeGPA(student.grades);
  const avg = average(student.grades);
  y += 8;
  doc.setFillColor(...LIGHT);
  doc.roundedRect(14, y, w - 28, 24, 3, 3, "F");
  doc.setFont("helvetica", "bold");
  doc.setFontSize(12);
  doc.text(`Cumulative GPA: ${fmtGPA(gpa)} / 4.00`, 20, y + 10);
  doc.setFont("helvetica", "normal");
  doc.setFontSize(10);
  doc.text(`Average score: ${avg === null ? "N/A" : avg.toFixed(1) + "%"}`, 20, y + 18);
  const remark =
    gpa === null ? "No grades recorded" : gpa >= 3.5 ? "Outstanding performance" : gpa >= 2.5 ? "Good performance" : gpa >= 1.7 ? "Satisfactory - room to improve" : "Needs additional support";
  doc.text(`Remark: ${remark}`, w - 20, y + 14, { align: "right" });

  // bar chart
  y += 34;
  if (subjects.length) {
    doc.setFont("helvetica", "bold");
    doc.setFontSize(11);
    doc.text("Performance by subject", 14, y);
    y += 6;
    subjects.forEach((s) => {
      const v = Number(student.grades[s]) || 0;
      doc.setFont("helvetica", "normal");
      doc.setFontSize(9);
      doc.text(s, 14, y + 4);
      doc.setFillColor(226, 232, 240);
      doc.rect(55, y, 110, 5, "F");
      if (v >= 75) doc.setFillColor(16, 185, 129);
      else if (v >= 60) doc.setFillColor(245, 158, 11);
      else doc.setFillColor(244, 63, 94);
      doc.rect(55, y, (110 * Math.min(100, v)) / 100, 5, "F");
      doc.text(`${v}%`, 170, y + 4);
      y += 8;
    });
  }

  footer(doc);
  doc.save(`Report_${student.id}_${student.name.replace(/\s+/g, "_")}.pdf`);
}

export function schoolReport(students) {
  const doc = new jsPDF();
  header(doc, "School Performance Summary", new Date().toLocaleDateString());
  const ranked = students
    .map((s) => ({ s, g: computeGPA(s.grades), a: average(s.grades) }))
    .sort((a, b) => (b.g ?? -1) - (a.g ?? -1));
  const valid = ranked.filter((x) => x.g !== null);
  const avgGpa = valid.reduce((a, x) => a + x.g, 0) / (valid.length || 1);
  const avgAtt = students.reduce((a, s) => a + Number(s.attendance || 0), 0) / (students.length || 1);

  doc.setFont("helvetica", "bold");
  doc.setFontSize(12);
  doc.text("Overview", 14, 46);
  doc.setFont("helvetica", "normal");
  doc.setFontSize(10);
  doc.text(`Total students: ${students.length}`, 14, 54);
  doc.text(`Average GPA: ${avgGpa.toFixed(2)}`, 80, 54);
  doc.text(`Average attendance: ${avgAtt.toFixed(1)}%`, 140, 54);

  const cols = [
    { label: "Rank", x: 17 },
    { label: "ID", x: 32 },
    { label: "Student", x: 54, max: 28 },
    { label: "Class", x: 108 },
    { label: "Avg %", x: 130, align: "center" },
    { label: "GPA", x: 155, align: "center" },
    { label: "Attendance", x: 185, align: "center" },
  ];
  const rows = ranked.map((x, i) => [
    i + 1,
    x.s.id,
    x.s.name,
    x.s.cls,
    x.a === null ? "-" : x.a.toFixed(1),
    fmtGPA(x.g),
    x.s.attendance + "%",
  ]);
  paged(doc, 62, cols, rows);

  // subject averages on new section
  const h = doc.internal.pageSize.getHeight();
  let y = doc.lastAutoY || 0;
  doc.addPage();
  y = 20;
  doc.setFont("helvetica", "bold");
  doc.setFontSize(12);
  doc.text("Subject averages", 14, y);
  y += 8;
  SUBJECTS.forEach((sub) => {
    const vals = students.map((s) => Number(s.grades?.[sub.name])).filter((n) => !Number.isNaN(n));
    const avg = vals.length ? vals.reduce((a, b) => a + b, 0) / vals.length : 0;
    doc.setFont("helvetica", "normal");
    doc.setFontSize(10);
    doc.text(sub.name, 14, y + 4);
    doc.setFillColor(226, 232, 240);
    doc.rect(60, y, 110, 5, "F");
    doc.setFillColor(...INDIGO);
    doc.rect(60, y, (110 * avg) / 100, 5, "F");
    doc.text(`${avg.toFixed(1)}%`, 175, y + 4);
    y += 10;
    if (y > h - 24) {
      doc.addPage();
      y = 20;
    }
  });

  footer(doc);
  doc.save("EduSphere_School_Summary.pdf");
}

