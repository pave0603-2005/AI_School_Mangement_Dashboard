export function transportReport(buses) {
  const doc = new jsPDF();
  header(doc, "Transport Status Report", new Date().toLocaleString());
  const cols = [
    { label: "Bus", x: 17 },
    { label: "Route", x: 40, max: 22 },
    { label: "Driver", x: 90, max: 14 },
    { label: "Status", x: 124, max: 14 },
    { label: "Speed", x: 158, align: "center" },
    { label: "Delay", x: 176, align: "center" },
    { label: "Onboard", x: 195, align: "center" },
  ];
  paged(
    doc,
    44,
    cols,
    buses.map((b) => [
      b.id,
      b.route.name,
      b.route.driver,
      b.status,
      `${Math.round(b.speed)} km/h`,
      `${b.delay.toFixed(1)} m`,
      `${b.onboard}/${b.route.capacity}`,
    ])
  );
  footer(doc);
  doc.save("EduSphere_Transport_Report.pdf");
}
